<#
.SYNOPSIS
  Builds VRModLoader.exe with the C# compiler that ships with Windows (.NET Framework 4.8) - no SDK, no NuGet.
.EXAMPLE
  .\build.ps1              # build + desktop shortcut
  .\build.ps1 -Run         # build, then start it
  .\build.ps1 -RebuildIcon # redraw assets\app.ico first
#>
param(
    [switch]$Run,
    [switch]$RebuildIcon,
    [switch]$NoShortcut,
    # Build somewhere else (e.g. build\VRModLoader.exe) without touching - or killing - the running launcher.
    [string]$Out,
    # Increment the VERSION file before building: patch | minor | major
    [ValidateSet('', 'patch', 'minor', 'major')]
    [string]$Bump = ''
)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
Set-Location $root

# ---- version: single source of truth is the VERSION file; Version.cs is generated from it ----
$versionFile = Join-Path $root 'VERSION'
if (-not (Test-Path $versionFile)) { Set-Content $versionFile '1.0.0' -Encoding ASCII }
$version = (Get-Content $versionFile -Raw).Trim()
if ($version -notmatch '^(\d+)\.(\d+)\.(\d+)$') { throw "VERSION must look like 1.2.3 (found '$version')" }
if ($Bump) {
    $maj = [int]$Matches[1]; $min = [int]$Matches[2]; $pat = [int]$Matches[3]
    switch ($Bump) { 'major' { $maj++; $min = 0; $pat = 0 } 'minor' { $min++; $pat = 0 } 'patch' { $pat++ } }
    $version = "$maj.$min.$pat"
    Set-Content $versionFile $version -Encoding ASCII
    Write-Host ">> version bumped ($Bump) -> $version" -ForegroundColor Cyan
}
$commit = 'nogit'
try { $c = (git -C $root rev-parse --short HEAD 2>$null); if ($LASTEXITCODE -eq 0 -and $c) { $commit = $c.Trim(); if ((git -C $root status --porcelain 2>$null | Where-Object { $_ -notmatch 'src/Version.cs' })) { $commit += '-dirty' } } } catch { }
$builtAt = Get-Date -Format 'yyyy-MM-dd HH:mm'
$versionCs = @"
// <auto-generated> by build.ps1 from the VERSION file - do not edit, do not bump by hand </auto-generated>
using System.Reflection;

[assembly: AssemblyVersion("$version.0")]
[assembly: AssemblyFileVersion("$version.0")]
[assembly: AssemblyInformationalVersion("$version+$commit")]

namespace VRModLoader
{
    internal static class BuildInfo
    {
        public const string Version = "$version";
        public const string Commit = "$commit";
        public const string BuiltAt = "$builtAt";
    }
}
"@
Set-Content (Join-Path $root 'src\Version.cs') $versionCs -Encoding UTF8
Write-Host ">> version $version ($commit)" -ForegroundColor Cyan

$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { $csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\csc.exe' }
if (-not (Test-Path $csc)) { throw "csc.exe not found - .NET Framework 4.x is required (it ships with Windows)." }

$ico = Join-Path $root 'assets\app.ico'
if ($RebuildIcon -or -not (Test-Path $ico)) {
    Write-Host '>> drawing icon' -ForegroundColor Cyan
    & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $root 'tools\make-icon.ps1') -Out $ico
}

$staged = -not [string]::IsNullOrEmpty($Out)
$out = if ($staged) { $Out } else { Join-Path $root 'VRModLoader.exe' }
if (-not [System.IO.Path]::IsPathRooted($out)) { $out = Join-Path $root $out }
$outDir = Split-Path $out -Parent
if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }
$manifest = Join-Path $root 'src\app.manifest'
$sources = Get-ChildItem (Join-Path $root 'src') -Filter *.cs | ForEach-Object { $_.FullName }
$refs = 'System.dll', 'System.Core.dll', 'System.Drawing.dll', 'System.Windows.Forms.dll',
        'System.Web.Extensions.dll', 'System.Management.dll', 'System.ServiceProcess.dll', 'Microsoft.CSharp.dll'

if (-not $staged -and (Get-Process VRModLoader -ErrorAction SilentlyContinue)) {
    Write-Host '>> VRModLoader is running - closing it so the exe can be replaced' -ForegroundColor Yellow
    Get-Process VRModLoader | Stop-Process -Force
    Start-Sleep -Milliseconds 800
}

Write-Host ">> compiling $($sources.Count) files with $csc" -ForegroundColor Cyan
$args = @(
    '/nologo', '/target:winexe', '/platform:anycpu', '/optimize+', '/warn:3', '/nowarn:1591,0618',
    "/out:$out",
    "/win32icon:$ico",
    "/win32manifest:$manifest",
    "/resource:$ico,app.ico"
) + ($refs | ForEach-Object { "/r:$_" }) + $sources

& $csc @args
if ($LASTEXITCODE -ne 0) { throw "csc failed with exit code $LASTEXITCODE" }
$exe = Get-Item $out
Write-Host (">> built {0}  ({1:N0} bytes, {2})" -f $exe.FullName, $exe.Length, $exe.LastWriteTime) -ForegroundColor Green

if (-not $NoShortcut -and -not $staged) {
    $desktop = [Environment]::GetFolderPath('Desktop')
    $lnk = Join-Path $desktop 'VR Mod Loader.lnk'
    $shell = New-Object -ComObject WScript.Shell
    $sc = $shell.CreateShortcut($lnk)
    $sc.TargetPath = $out
    $sc.WorkingDirectory = $root
    $sc.IconLocation = "$out,0"
    $sc.Description = 'Launch Titanfall 2 VR with the whole VR stack, in order, with logs'
    $sc.Save()
    Write-Host ">> desktop shortcut: $lnk" -ForegroundColor Green
}

if ($Run) { Start-Process $out -WorkingDirectory $root }
